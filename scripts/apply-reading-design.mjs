import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative } from 'node:path';

const out = 'dist';
const css = await readFile('public/reading.css', 'utf8');
const version = createHash('sha256').update(css).digest('hex').slice(0, 12);
await writeFile(join(out, 'reading.css'), css);
const stylesheet = `<link rel="stylesheet" href="/reading.css?v=${version}" data-reading-design>`;

// Keep the article and its evidence visible; offer the repeated practice,
// research and agent links in one native, keyboard-accessible disclosure.
const moreLabels = {
  en: 'More ways to use this idea',
  ru: 'Дополнительные материалы и практика',
  de: 'Weitere Materialien und Übungen',
  fr: 'Pour aller plus loin et pratiquer',
  es: 'Más recursos y práctica',
  'pt-br': 'Mais recursos e prática',
  it: 'Altre risorse e pratica',
};
const relatedLabels = {
  en: 'Related comparisons and decision contexts',
  ru: 'Сравнения и контексты решений',
  de: 'Vergleiche und Entscheidungskontexte',
  fr: 'Comparaisons et contextes de décision',
  es: 'Comparaciones y contextos de decisión',
  'pt-br': 'Comparações e contextos de decisão',
  it: 'Confronti e contesti decisionali',
};

function simplifyReadingPage(html) {
  const language = html.match(/<html\b[^>]*lang="([^"]+)"/)?.[1]?.toLowerCase() || 'en';
  // Start with the definition, then the illustration. Preserve the actual image
  // element and all discovery metadata generated by the image pipeline.
  html = html.replace(/(<figure class="article-visual">[\s\S]*?<\/figure>)\s*(<p class="definition">[\s\S]*?<\/p>)/, '$2$1');
  if (!html.includes('class="reading-related"')) {
    html = html.replace(/((?:<aside class="(?:comparison-teaser|audit-cta|context-teaser)"[^>]*>[\s\S]*?<\/aside>\s*){2,})/, (content) =>
      `<details class="reading-related"><summary>${relatedLabels[language] || relatedLabels.en}</summary>${content}</details>`);
  }
  html = html.replace(/(<main\b[^>]*>)([\s\S]*?)(<\/main>)/, (match, open, content, close) => {
    if (content.includes('class="reading-more"')) return match;
    const articleEnd = content.lastIndexOf('</article>');
    if (articleEnd < 0) return match;
    const split = articleEnd + '</article>'.length;
    const tail = content.slice(split);
    if (!/^\s*(?:<aside class="(?:practice|research|everyday|experiment)-teaser"|<section class="section section--ink")/.test(tail)) return match;
    const label = moreLabels[language] || moreLabels.en;
    let article = content.slice(0, split);
    const legacy = article.match(/<section class="related legacy-related">[\s\S]*?<\/section>/)?.[0] || '';
    if (legacy) article = article.replace(legacy, '');
    return `${open}${article}<details class="reading-more"><summary>${label}</summary><div class="reading-more__body">${legacy}${tail}</div></details>${close}`;
  });
  // The site announcement stays available after the reading experience.
  const announcement = html.match(/<aside class="vedokrok-banner" data-vedokrok-banner>[\s\S]*?<\/aside>/)?.[0];
  if (announcement && html.includes('</main>')) {
    html = html.replace(announcement, '').replace('</main>', `</main>${announcement}`);
  }
  return html;
}

async function htmlFiles(directory) {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const file = join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await htmlFiles(file));
    else if (entry.isFile() && entry.name.endsWith('.html')) files.push(file);
  }
  return files;
}

let pages = 0;
for (const file of await htmlFiles(out)) {
  const source = await readFile(file, 'utf8');
  if (!source.includes('</head>')) continue;
  const route = relative(out, file).replaceAll('\\', '/').replace(/^(?:de|ru|fr|es|it|pt-br)\//, '');
  const isReadingPage = /^(?:biases|biais|sesgos|vieses|bias|bias-cognitivi|contexts|situations|techniques|tecnicas|tecniche|compare|everyday|research|skills|habilidades|competenze)\/[^/]+\//.test(route);
  let next = source.replace(/<link\b[^>]*\bdata-reading-design[^>]*>/g, '');
  next = next.replace('</head>', `${stylesheet}</head>`);
  next = next.replace(/\sdata-reading-page(?:="[^"]*")?/g, '');
  if (isReadingPage) {
    next = next.replace(/<body\b/, '<body data-reading-page');
    next = simplifyReadingPage(next);
  }
  if (next !== source) await writeFile(file, next);
  pages += 1;
}
console.log(`Reading design applied after theme/localization styles on ${pages} pages (${version}).`);
